#!/usr/bin/env node
// Regenerates packages/core/src/tokenizer/claude/vocab-v4-7.ts from ctok's pieces_v4_7.json.
//
//   node packages/core/scripts/gen-claude-vocab.mjs <path/to/ctok/data/pieces_v4_7.json>
//
// Source: https://github.com/sanderland/ctok (MIT), commit 8c43ffd3c7be467622a540f025516e49ef78d8b1.
// The upstream file carries a witness record per piece; the engine reads only the piece
// spellings, so this keeps the spellings and the family scalars and drops the witnesses.
// Pieces are stored in ctok's internal glyph form: `parse_marked` (ctok/notation.py) is applied
// here, so the runtime never parses the ⟨bow⟩/⟨0xNN⟩ notation.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const CTOK_COMMIT = '8c43ffd3c7be467622a540f025516e49ef78d8b1';
const OUT = resolve(
  dirname(fileURLToPath(import.meta.url)),
  '../src/tokenizer/claude/vocab-v4-7.ts',
);

// ctok/constants.py ATOM_TO_GLYPH. ⟨pad⟩ has no glyph form and stays as its atom text.
const ATOM_TO_GLYPH = new Map([
  ['⟨bow⟩', '\uFDD0'],
  ['⟨eow⟩', '\uFDD1'],
  ['⟨shift⟩', '\uFDD3'],
  ['⟨caps⟩', '\uFDD4'],
]);
const ATOM_RE = /⟨(?:bow|eow|shift|caps|pad|0x[0-9A-Fa-f]{2})⟩|./gsu;
const BYTE_ATOM_RE = /^⟨0x([0-9A-Fa-f]{2})⟩$/u;
const utf8 = new TextDecoder('utf-8', { fatal: true });

/** Port of ctok.notation.parse_marked. */
function parseMarked(pub) {
  let out = '';
  let buf = [];
  const flush = () => {
    if (buf.length > 0) {
      out += utf8.decode(Uint8Array.from(buf));
      buf = [];
    }
  };
  for (const [tok] of pub.matchAll(ATOM_RE)) {
    if ([...tok].length === 1) {
      flush();
      out += tok;
      continue;
    }
    const glyph = ATOM_TO_GLYPH.get(tok);
    if (glyph !== undefined) {
      flush();
      out += glyph;
      continue;
    }
    const byte = BYTE_ATOM_RE.exec(tok);
    if (byte) {
      buf.push(Number.parseInt(byte[1], 16));
    } else {
      flush();
      out += tok;
    }
  }
  flush();
  return out;
}

/**
 * A single-quoted TS string literal holding only printable ASCII. `$` is escaped too, so a
 * piece spelled `${` does not trip biome's noTemplateCurlyInString.
 */
function tsString(s) {
  let out = "'";
  for (let i = 0; i < s.length; i++) {
    const c = s.charCodeAt(i);
    if (c === 0x5c) out += '\\\\';
    else if (c === 0x27) out += "\\'";
    else if (c >= 0x20 && c < 0x7f && c !== 0x24) out += s[i];
    else out += `\\u${c.toString(16).toUpperCase().padStart(4, '0')}`;
  }
  return `${out}'`;
}

const src = process.argv[2];
if (!src) {
  console.error('usage: gen-claude-vocab.mjs <path/to/pieces_v4_7.json>');
  process.exit(2);
}
const doc = JSON.parse(readFileSync(src, 'utf8'));
const { meta, tokens } = doc;
if (meta.family !== 'v4.7') throw new Error(`expected the v4.7 vocabulary, got ${meta.family}`);

const pieces = [];
for (const [group, entries] of Object.entries(tokens)) {
  if (group === 'bytes_fallback' || group === 'contractions' || group === 'markers') continue;
  for (const p of Object.keys(entries)) pieces.push(parseMarked(p));
}
const contractions = Object.keys(tokens.contractions);
for (const c of contractions) {
  // engine.build_vocab glues the raw key; parse_marked must leave it unchanged for the two
  // readings to agree.
  if (parseMarked(c) !== c) throw new Error(`contraction ${c} uses marker notation`);
}
const markers = Object.keys(tokens.markers).map(parseMarked);
const bytesFallback = Object.keys(tokens.bytes_fallback);
for (const h of bytesFallback) {
  if (!/^(?:[0-9a-f]{2})+$/.test(h)) throw new Error(`bad byte prefix ${h}`);
}

const data = {
  meta: {
    family: meta.family,
    sourceModel: meta.source_model,
    built: meta.built,
    messageOverhead: meta.message_overhead,
    foldQuotes: meta.fold_quotes,
    allcapsMin: meta.allcaps_min,
  },
  pieces,
  contractions,
  markers,
  bytesFallback,
};

const body = [
  '// Generated by packages/core/scripts/gen-claude-vocab.mjs. Do not edit by hand.',
  `// Derived from ctok ctok/data/pieces_v4_7.json (https://github.com/sanderland/ctok, commit`,
  `// ${CTOK_COMMIT}), MIT, Copyright (c) 2026 Sander Land; see ./LICENSE.`,
  '// Pieces are in ctok internal glyph form (U+FDD0 bow, U+FDD1 eow, U+FDD3 shift, U+FDD4 caps).',
  '// Kept as a JSON string so the module is cheap to import; claude/engine.ts parses it on first use.',
  // The `: string` annotation keeps tsc from copying the whole literal into the .d.ts.
  `export const VOCAB_V4_7_JSON: string =\n  ${tsString(JSON.stringify(data))};`,
  '',
].join('\n');
writeFileSync(OUT, body, 'utf8');
console.log(
  `wrote src/tokenizer/claude/vocab-v4-7.ts: ${pieces.length} pieces, ` +
    `${contractions.length} contractions, ${markers.length} markers, ` +
    `${bytesFallback.length} byte prefixes, ${body.length} bytes`,
);
